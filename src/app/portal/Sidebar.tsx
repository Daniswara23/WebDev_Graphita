export default function Sidebar({ adminName }: { adminName: string }) {
const pathname = usePathname();

  // Memoize pattern check to reduce re-computation on re-renders
  const isActiveItem = (itemHref: string) => {
    return pathname === itemHref || pathname.startsWith(itemHref + "/");
  };

  return (
    <aside className={styles.aside}>
      {/* Logo */}
      <div className={styles.logo}>
        <Link href="/portal/dashboard" className={styles.logoLink}>
          <img src="/images/logo-GAS.png" alt="Grahita Adhi Sasmita" className={styles.logoImg} />
        </Link>
      </div>

      {/* Admin name */}
      <div className={styles.adminName}>
        {adminName}
      </div>

      {/* Theme Toggle */}
      <div style={{ padding: "12px 24px", borderBottom: "1px solid var(--card-border)" }}>
        <ThemeToggle />
      </div>

      {/* Navigation */}
      <nav className={styles.nav}>
        {NAV_ITEMS.map((item) => (
          <Link
            key={item.href}
            href={item.href}
            className={`${styles.navLink} ${isActiveItem(item.href) ? styles.navLinkActive : ""}`}
          >
            <span className={styles.navIcon}>{item.icon}</span>
            {item.label}
          </Link>
        ))}
      </nav>

      {/* Logout */}
      <div className={styles.footer}>
        <form action={logoutAction}>
          <button type="submit" className={styles.logoutBtn}>
            Keluar
          </button>
        </form>
      </div>
    </aside>
  );
}